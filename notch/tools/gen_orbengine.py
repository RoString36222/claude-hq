#!/usr/bin/env python3
"""Regenerate notch/Sources/HQNotch/OrbEngineJS.swift from ui/orbs.js (the vendored
thinking-orbs engine, without HQ's DOM mount layer), so the notch's orbs never drift from HQ's.

    python3 notch/tools/gen_orbengine.py          # rewrite OrbEngineJS.swift
    python3 notch/tools/gen_orbengine.py --check  # exit 1 if it is out of date
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "ui", "orbs.js")
OUT = os.path.join(REPO, "notch", "Sources", "HQNotch", "OrbEngineJS.swift")
MOUNT = "/* ---- thinking orbs: mount layer"


def render(js):
    cut = js.find(MOUNT)
    if cut < 0:
        raise SystemExit("gen_orbengine: mount-layer marker not found in %s" % SRC)
    engine = js[:cut].rstrip() + "\n"
    if '"""##' in engine:
        raise SystemExit("gen_orbengine: engine contains the raw-string delimiter")
    return ("// GENERATED by notch/tools/gen_orbengine.py from ui/orbs.js. Do not edit.\n"
            "// The thinking-orbs engine (MIT, see the header inside), run by OrbEngine in JavaScriptCore.\n\n"
            "enum OrbEngineJS {\n    static let source = ##\"\"\"\n" + engine + "\"\"\"##\n}\n")


def main():
    with open(SRC, encoding="utf-8") as f:
        out = render(f.read())
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            sys.exit(0 if f.read() == out else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)


if __name__ == "__main__":
    main()
